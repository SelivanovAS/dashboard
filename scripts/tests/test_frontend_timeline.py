@pytest.mark.skipif(NODE is None, reason="node недоступен — поведенческий тест пропущен")
def test_peel_legacy_text_behaviour():
    """Исполняем настоящий хелпер из app.js в node на реальных фикстурах."""
    payload = json.dumps([{"text": t, "time": tm} for t, tm, _ in PEEL_CASES],
                         ensure_ascii=False)
    script = (_peel_fn_source()
              + "\nconst cases=" + payload + ";"
              + "\nprocess.stdout.write(JSON.stringify("
                "cases.map(c=>peelLegacyText(c.text,c.time))));")
    out = subprocess.run([NODE, "-e", script], capture_output=True,
                         text=True, check=True)
    results = json.loads(out.stdout)
    for (text, _tm, expected), got in zip(PEEL_CASES, results):
        assert got == expected, f"peelLegacyText({text!r}):\n{got}\n!=\n{expected}"
        # Инвариант юриста «ни один символ не теряется»: каждый выщип снимает
        # ровно сегмент + один разделитель «. » (2 символа), остальное — в имени.
        removed = sum(len(s) + 2
                      for s in (got["время"], got["место"], got["размещено"]) if s)
        assert len(text) == len(got["имя"]) + removed, (
            f"Потеря символов в peelLegacyText({text!r}): "
            f"{len(text)} != {len(got['имя'])} + {removed}"
        )

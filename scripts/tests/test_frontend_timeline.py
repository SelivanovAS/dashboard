@pytest.mark.skipif(NODE is None, reason="node недоступен — поведенческий тест пропущен")
def test_peel_legacy_text_behaviour():
    """Исполняем настоящий хелпер из app.js в node на реальных фикстурах."""
    payload = json.dumps([{"text": t, "time": tm} for t, tm, _ in PEEL_CASES],
                         ensure_ascii=False)
    script = (_peel_fn_source()
              + "\nconst cases=" + payload + ";"
              + "\nprocess.stdout.write(JSON.stringify("
                "cases.map(c=>peelLegacyText(c.text,c.time))));")
    out = subprocess.run([NODE, "-e", script], capture_output=True,
                         text=True, check=True)
    results = json.loads(out.stdout)
    for (text, _tm, expected), got in zip(PEEL_CASES, results):
        assert got == expected, f"peelLegacyText({text!r}):\n{got}\n!=\n{expected}"
        # Инвариант юриста «ни один символ не теряется»: каждый выщип снимает
        # ровно сегмент + один разделитель «. » (2 символа), остальное — в имени.
        removed = sum(len(s) + 2
                      for s in (got["время"], got["место"], got["размещено"]) if s)
        assert len(text) == len(got["имя"]) + removed, (
            f"Потеря символов в peelLegacyText({text!r}): "
            f"{len(text)} != {len(got['имя'])} + {removed}"
        )


# ===== tlItemView: чистый вьюер строки хронологии =====
# UX утверждён юристом: у заседаний время — в строке даты («27.07.2026 · 14:00»)
# с бейджем/цветом срочности у будущих; у служебных — тихий штамп
# («31.03.2026, 13:22»); зал — отдельная заметная строка; «размещено …» —
# всегда отдельная самая тихая строка; между будущим и прошлым — водораздел.


def _fn_src(name: str) -> str:
    """Вырезать чистую функцию из app.js (конец — `}` в нулевой колонке)."""
    m = re.search(r"function\s+" + re.escape(name) + r"\s*\([\s\S]*?\n\}", _app_js())
    assert m, f"В app.js нет функции {name} — см. комментарий к tlItemView."
    return m.group(0)


def test_tl_item_view_wired_into_render():
    """Слоты строки собирает tlItemView, а renderDrawer только оборачивает их
    в HTML — иначе логика вьюера снова станет нетестируемой инлайн-склейкой."""
    src = _app_js()
    assert re.search(r"function\s+tlItemView\s*\(", src), (
        "В app.js нет tlItemView — сборка слотов строки хронологии должна "
        "жить в отдельной чистой функции (как peelLegacyText)."
    )
    assert len(re.findall(r"tlItemView\s*\(", src)) >= 2, (
        "tlItemView объявлена, но не вызывается из renderDrawer."
    )
    for cls in ("tl-time", "tl-stamp", "tl-place", "tl-rel", "tl-divider"):
        assert cls in src, (
            f"В разметке хронологии нет класса {cls} — потерян слот нового UX "
            "(время заседания / служебный штамп / зал / бейдж срочности / "
            "водораздел «уже было»)."
        )



def test_role_badges_are_graphite_in_both_themes():
    """Роли не красятся цветами стадий, а токен объявлен в обеих темах."""
    css = _read("styles.css")
    for селектор in (".badge-appellant", ".badge-cassator"):
        m = re.search(re.escape(селектор) + r"\s*\{([^}]*)\}", css)
        assert m, f"Правило {селектор} пропало."
        правило = m.group(1)
        assert "--role-badge-bg" in правило and "--role-badge-fg" in правило, (
            f"{селектор} красится мимо токенов роли — гамма снова разъедется "
            "со стадиями."
        )
        for занятое in ("--violet-", "--rose-", "--indigo-"):
            assert занятое not in правило, (
                f"{селектор} вернулся на {занятое}*: холодная ось занята "
                "бейджами стадий (violet — это «Кассация»)."
            )
    # Токен обязан быть в обоих блоках темы: светлый :root и dark.
    dark_start = css.index('[data-theme="dark"]')
    assert "--role-badge-fg" in css[:dark_start], "Токен роли не объявлен в светлой теме."
    assert "--role-badge-fg" in css[dark_start:], (
        "Токен роли не объявлен в тёмной теме — повторится история --rose-*, "
        "который светился светло-розовым кирпичом на тёмном фоне."
    )
    # Комментарии срезаем: в них имя токена упомянуто намеренно — объяснением,
    # почему его не возвращать.
    без_комментариев = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    assert "--rose-" not in без_комментариев, (
        "Токены --rose-* вернулись: у них не было тёмного варианта, а "
        "единственный потребитель (бейдж «Кассатор») переведён на графит."
    )


def test_badges_have_no_hardcoded_colours():
    """Цвет бейджа — только через токен, объявленный в ОБЕИХ темах.

    Класс дефектов, вскрытый юристом 14.08.2026: цвет, зашитый литералом в
    правило бейджа, тёмного варианта не получает никогда. Так светили на
    тёмном фоне «Кассатор» (--rose-* без dark), «Без движения»
    (#ffedd5/#c2410c) и рамка «Передано в 1-ю инст.» (#fecaca), а
    `var(--amber-800,#92400e)` ставил тёмно-коричневый текст на тёмный фон
    (токена --amber-800 в проекте нет — фолбэк маскировал опечатку).
    Литерал #fff разрешён: белый текст на насыщенной заливке верен в обеих
    темах.
    """
    css = _read("styles.css")
    нарушения = []
    for строка in css.splitlines():
        s = строка.strip()
        if not s.startswith(".badge"):
            continue
        тело = s[s.index("{") + 1 :] if "{" in s else ""
        # var(--токен, #литерал) — фолбэк прячет опечатку в имени токена
        if re.search(r"var\(\s*--[\w-]+\s*,\s*#", тело):
            нарушения.append((s[:60], "литеральный фолбэк в var()"))
            continue
        цвета = [
            c
            for c in re.findall(r"#[0-9a-fA-F]{3,8}", тело)
            if c.lower() not in ("#fff", "#ffffff")
        ]
        if цвета:
            нарушения.append((s[:60], str(цвета)))
    assert not нарушения, (
        "Цвет бейджа зашит литералом — в тёмной теме он останется светлым:\n"
        + "\n".join(f"  {сел} → {что}" for сел, что in нарушения)
    )



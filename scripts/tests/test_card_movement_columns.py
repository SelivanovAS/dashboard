"""
Структурные колонки «Движения дела» и «Движения жалобы».

Парсер склеивает ячейки строки в поле `text` и ДОПОЛНИТЕЛЬНО раскладывает их
по колонкам (name/place/result_event/ground/note/posted_at) — теми же именами,
что давно использует парсер кассации, чтобы фронт имел один рендерер на три
инстанции.

Главный охраняемый инвариант: поле `text` не меняется НИ НА СИМВОЛ. По паре
(date, text) события дедуплицирует `_events_newly_match` (lifecycle.py), и
смена формата склейки объявила бы всю историю каждого дела новой — юристу
ушёл бы дайджест-паводок.

Запуск: python3 -m pytest scripts/tests/test_card_movement_columns.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))))

from court_monitor import config  # noqa: E402
from court_monitor.parsing.cards import parse_case_card  # noqa: E402

ШАПКА = (
    "<tr><th>Наименование события</th><th>Дата</th><th>Время</th>"
    "<th>Место проведения</th><th>Результат события</th>"
    "<th>Основание для выбранного результата события</th>"
    "<th>Примечание</th>"
    "<th>Дата размещения&nbsp;Информация о размещении событий</th></tr>"
)

СТРОКА_ЗАСЕДАНИЯ = (
    "<tr><td>Судебное заседание</td><td>26.02.2026</td><td>11:00</td>"
    "<td>Зал судебного заседания 213</td><td>Вынесено решение по делу</td>"
    "<td>Иск (заявление, жалоба) УДОВЛЕТВОРЕН ЧАСТИЧНО</td><td></td>"
    "<td>29.01.2026</td></tr>"
)


def _карточка(строки: str, шапка: str = ШАПКА) -> dict:
    return parse_case_card(
        "<html><body><table><tr><td>ДВИЖЕНИЕ ДЕЛА</td></tr>"
        + шапка + строки + "</table></body></html>"
    )


def test_колонки_разложены():
    ev = _карточка(СТРОКА_ЗАСЕДАНИЯ)["_events"][0]
    assert ev["name"] == "Судебное заседание"
    assert ev["place"] == "Зал судебного заседания 213"
    assert ev["result_event"] == "Вынесено решение по делу"
    assert ev["ground"] == "Иск (заявление, жалоба) УДОВЛЕТВОРЕН ЧАСТИЧНО"
    assert ev["posted_at"] == "29.01.2026"
    # Пустая колонка «Примечание» в словарь не попадает — не раздуваем cases.json.
    assert "note" not in ev
    # Базовые date/time не перезаписаны сырым текстом ячейки (ключи карты
    # намеренно называются col_date/col_time).
    assert ev["date"] == "26.02.2026"
    assert ev["time"] == "11:00"
    assert "col_date" not in ev and "col_time" not in ev


def test_текст_события_не_изменился():
    """Golden: склейка байт-в-байт такая же, как в боевом cases.json."""
    ev = _карточка(СТРОКА_ЗАСЕДАНИЯ)["_events"][0]
    assert ev["text"] == (
        "Судебное заседание. 11:00. Зал судебного заседания 213. "
        "Вынесено решение по делу. "
        "Иск (заявление, жалоба) УДОВЛЕТВОРЕН ЧАСТИЧНО. 29.01.2026"
    )


СТРОКА_ЕДИНОЛИЧНОГО = (
    "<tr><td>Единоличное рассмотрение (без вызова лиц, участвующих в деле)"
    "</td><td>29.07.2026</td><td>00:00</td>"
    "<td>3 этаж зал № 8</td><td></td><td></td><td></td>"
    "<td>15.07.2026</td></tr>"
)


def test_единоличное_рассмотрение_это_заседание():
    """«Единоличное рассмотрение (без вызова лиц…)» (Свердловский облсуд) —
    session-событие: обязано давать «Дату/Время заседания». Иначе апелляции
    Урала невидимы как заседания: дайджест цитировал сырую склейку с датой
    размещения вместо даты рассмотрения (инцидент 30.07.2026)."""
    info = _карточка(СТРОКА_ЕДИНОЛИЧНОГО)
    assert info["Дата заседания"] == "29.07.2026"
    assert info["Время заседания"] == "00:00"


def test_единоличное_склейка_байт_в_байт():
    """Golden: расширение _SESSION_START_RX не смеет менять text —
    по паре (date, text) дедуплицирует _events_newly_match."""
    ev = _карточка(СТРОКА_ЕДИНОЛИЧНОГО)["_events"][0]
    assert ev["text"] == (
        "Единоличное рассмотрение (без вызова лиц, участвующих в деле). "
        "00:00. 3 этаж зал № 8. 15.07.2026"
    )
    assert ev["date"] == "29.07.2026"
    assert ev["time"] == "00:00"


def test_строка_шапки_не_попадает_в_события():
    """Шапка колонок оседала в _events мусорным событием с пустой датой —
    по одному на каждую карточку. Производные поля при этом не меняются."""
    info = _карточка(СТРОКА_ЗАСЕДАНИЯ)
    assert all(e["date"] for e in info["_events"])
    assert not any("Наименование события" in e["text"] for e in info["_events"])
    assert info["Дата заседания"] == "26.02.2026"
    assert info["Время заседания"] == "11:00"
    assert info["Последнее событие"].startswith("Судебное заседание")


def test_переставленные_колонки_разложены_по_шапке():
    """Раскладка идёт по заголовкам, а не по позиции: у 54 капчёвых судов
    Свердловской области порядок колонок никто не сверял."""
    шапка = (
        "<tr><th>Наименование события</th><th>Дата</th><th>Время</th>"
        "<th>Результат события</th><th>Место проведения</th>"
        "<th>Основание для выбранного результата события</th>"
        "<th>Примечание</th><th>Дата размещения</th></tr>"
    )
    строка = (
        "<tr><td>Судебное заседание</td><td>26.02.2026</td><td>11:00</td>"
        "<td>Вынесено решение по делу</td><td>Зал 213</td>"
        "<td>ОТКАЗАНО</td><td></td><td>29.01.2026</td></tr>"
    )
    ev = _карточка(строка, шапка)["_events"][0]
    assert ev["result_event"] == "Вынесено решение по делу"
    assert ev["place"] == "Зал 213"


def test_нестандартная_ширина_откатывается_в_legacy():
    """Ширина строки не совпала с шапкой — колонки не раскладываем вовсе.
    Честный отказ вместо тихой подстановки не туда; фронт покажет склейку."""
    config.METRICS["movement_odd_width"] = 0
    строка = (
        "<tr><td>Судебное заседание</td><td>26.02.2026</td><td>11:00</td>"
        "<td>Вынесено решение по делу</td></tr>"
    )
    ev = _карточка(строка)["_events"][0]
    assert set(ev) == {"date", "time", "text"}
    assert config.METRICS["movement_odd_width"] == 1


def test_без_распознанной_шапки_прежнее_поведение():
    """Шапки нет — работаем как раньше: только date/time/text."""
    info = parse_case_card(
        "<html><body><table><tr><td>ДВИЖЕНИЕ ДЕЛА</td></tr>"
        "<tr><td>Судебное заседание</td><td>26.02.2026</td><td>11:00</td></tr>"
        "</table></body></html>"
    )
    ev = info["_events"][0]
    assert set(ev) == {"date", "time", "text"}


def test_движение_жалобы_раскладывается():
    """У событий жалобы колонки те же, а text остаётся прежним
    («label · примечание») — по нему идёт дедуп в самом парсере."""
    info = parse_case_card(
        "<html><body>"
        "<table><tr><td>ЖАЛОБА № 1</td></tr>"
        "<tr><td>Вид жалобы (представления)</td><td>Апелляционная жалоба</td></tr>"
        "</table>"
        "<table><tr><td>ДВИЖЕНИЕ ЖАЛОБЫ</td></tr>"
        "<tr><th>Событие</th><th>Дата</th><th>Результат</th>"
        "<th>Основание</th><th>Примечание</th><th>Дата размещения</th></tr>"
        "<tr><td>Регистрация жалобы (представления) в суде</td>"
        "<td>15.01.2026</td><td>Принята к производству</td><td></td>"
        "<td>Срок до 27.04.2026</td><td>16.01.2026</td></tr>"
        "</table></body></html>"
    )
    события = info["_fi_appeal_events"]
    assert события, "движение жалобы не распозналось"
    ev = события[0]
    assert ev["date"] == "15.01.2026"
    assert ev["text"] == (
        "Регистрация жалобы (представления) в суде · Срок до 27.04.2026"
    )
    assert ev["name"] == "Регистрация жалобы (представления) в суде"
    assert ev["result_event"] == "Принята к производству"
    assert ev["note"] == "Срок до 27.04.2026"
    assert ev["posted_at"] == "16.01.2026"

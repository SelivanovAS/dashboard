#!/bin/bash
# =============================================================================
# Резерв: разбор очереди дампов по ВСЕМ территориям (без парсинга).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ДРАЙВЕР. parse_all.sh гоняет парсинг+дампы одним утренним
# заходом, а оператор кормит дампы до вечера: замер 18.08.2026 — вставки шли
# с 09:28 до 12:12, и всё, что облако потеряло (заблокированный адрес раннера),
# юрист подбирал руками в 11:54 и 12:14 (~94 иска банка). Этот драйвер зовёт
# import_dumps.sh по каждому клону и висит на СВОЁМ LaunchAgent
# (com.court-monitor.import: будни 10:30/12:30/14:30/16:30/18:30 — расписание
# юриста, 18.08.2026). Пустая очередь = выход за секунды; вне сети Сбера
# import_dumps.sh сам тихо пропускает.
#
# KV-бюджет: проверка очереди — один list-запрос; 5 слотов × 2 территории =
# 10 в день при лимите free-tier 1000 (инцидент 17.07.2026 — не наращивать).
#
# Запуск (обычно — LaunchAgent'ом; руками — из пульта «СберСуд-пульт.command»):
#   bash ops/mac-local-run/import_all.sh [--dry-run] [--anywhere] [--check]
# =============================================================================
set -u

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IMPORTER="$HERE/import_dumps.sh"
. "$HERE/lib_sber_net.sh"

repos=()
while IFS= read -r line; do
  repos+=("$line")
done < <(cm_territories)

echo "$(date '+%Y-%m-%d %H:%M:%S') import_all: территорий ${#repos[@]}"

# Территории независимы: отказ одной НЕ отменяет остальные (зеркало parse_all).
rc=0
for repo in "${repos[@]}"; do
  if [ ! -d "$repo/.git" ]; then
    echo "  ПРОПУСК: $repo — не похоже на клон репозитория"
    rc=1
    continue
  fi
  echo "  → $repo"
  bash "$IMPORTER" "$repo" "$@" || rc=1
done

echo "$(date '+%Y-%m-%d %H:%M:%S') import_all: готово (код $rc)"
exit "$rc"
